x_init = x_init / x_init.norm(dim=-1, keepdim=True)

# --- 2. Inference Wrapper (Fixes Time Broadcasting) ---
def inference_model(t, x):
    # The solver passes 't' as a scalar (0-dim).
    # The Transformer needs 't' as a vector (Batch-dim).
    if t.ndim == 0:
        # Create vector [t, t, t, ...] matching x's batch size
        t = torch.full((x.shape[0],), t.item(), device=x.device)

    # Forward pass: Model expects (x, t)
    return vf(x, t)

# --- 3. Run ODE Solver ---
step_size = 0.05
N = 20

solver = RiemannianODESolver(velocity_model=inference_model, manifold=manifold)

print(f"Generating {desired_batch_size} samples...")
sol = solver.sample(
    x_init=x_init,
    step_size=step_size,
    method="euler",
    return_intermediates=False,
    time_grid=torch.linspace(0, 1, N).to(device),
    verbose=True,
)

# --- 4. Dynamic Decoding (Fixes Shape Error) ---
final_x = sol[-1] # Get the final state

# Calculate how many full sentences exist in the output
# This prevents crashes if the batch dimension was squeezed or altered
total_elements = final_x.numel()
sentence_size = flat_dim

actual_batch_size = total_elements // sentence_size

print(f"DEBUG: Output Elements: {total_elements}")
print(f"DEBUG: Reshaping to Batch Size: {actual_batch_size}")

if actual_batch_size == 0:
    raise ValueError(f"Output size {total_elements} is smaller than a single sentence ({sentence_size})!")

# Reshape safely: (Batch, SeqLen, Vocab)
final_x = final_x.view(actual_batch_size, target_seq_len, target_vocab)

# --- 5. Convert to Text ---
# Inverse Fisher Transform: Probabilities = x^2
