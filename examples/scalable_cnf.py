    # Gaussian noise usually has norm sqrt(dim). We must normalize it too.
    x_0 = torch.randn_like(x_1)
    x_0 = x_0 / x_0.norm(dim=-1, keepdim=True)

    # sample time (user's responsibility)
    t = torch.rand(x_1.shape[0]).to(device)

    # sample probability path
    path_sample = path.sample(t=t, x_0=x_0, x_1=x_1)
    pred_v = vf(path_sample.x_t, path_sample.t)

    # flow matching l2 loss
    loss = torch.pow(pred_v - path_sample.dx_t, 2).sum()

    # optimizer step
    loss.backward() # backward
    optim.step() # update

    # log loss
    if (i+1) % print_every == 0:
        elapsed = time.time() - start_time
        target_magnitude = path_sample.dx_t.abs().mean().item()

